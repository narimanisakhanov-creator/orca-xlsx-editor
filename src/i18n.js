const TABLES = { en: EN, ru: RU }

/** Russian for `ru`/`ru-RU`; English for everything else, including an absent tag. */
export function resolveLocale(tag) {
  return typeof tag === 'string' && /^ru(?:[-_]|$)/i.test(tag.trim()) ? 'ru' : 'en'
}

/** Translate a key and fill `{name}` placeholders. Unknown keys fall back to English, then the key. */
export function t(locale, key, values = {}) {
  const table = TABLES[locale] ?? EN
  const template = table[key] ?? EN[key] ?? key
  return template.replace(/\{(\w+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : whole)
}

/** Agent state label; unknown states stay empty, as before. */
export function agentState(locale, state) {
  return state && Object.prototype.hasOwnProperty.call(TABLES[locale] ?? EN, `agent.state.${state}`)
    ? t(locale, `agent.state.${state}`)
    : ''
}

